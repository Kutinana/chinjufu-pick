export function localizedCount(count: number, unit: 'ships' | 'entries' | 'artworks', language: Language): string {
  const singular = { ships: 'shipgirl', entries: 'candidate', artworks: 'illustration' };
  const label = language === 'en' && count === 1 ? singular[unit] : messages[language][unit];
  return `${count.toLocaleString(language)} ${label}`;
}
export function initialLanguage(): Language {
  const query = new URLSearchParams(location.search).get('lang');
  if (query === 'zh' || query === 'ja' || query === 'en') return query;
  try {
    const saved = localStorage.getItem('chinjufu-language');
    if (saved === 'zh' || saved === 'ja' || saved === 'en') return saved;
  } catch { /* Browser storage may be unavailable. */ }
  return navigator.language.startsWith('zh') ? 'zh' : navigator.language.startsWith('ja') ? 'ja' : 'en';
}
